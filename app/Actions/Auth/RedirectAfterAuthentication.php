<?php

namespace App\Actions\Auth;

use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Routing\Router;
use Symfony\Component\HttpKernel\Exception\MethodNotAllowedHttpException;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;

class RedirectAfterAuthentication
{
    public function __construct(private Router $router) {}

    public function execute(Request $request, array $fallbackParameters = []): RedirectResponse
    {
        if (! $request->user()->hasVerifiedEmail()) {
            return to_route('verification.notice');
        }

        $target = $request->session()->pull('url.intended');
        if (is_string($target) && $this->isAccessiblePage($request, $target)) {
            return redirect()->to($target);
        }

        return to_route('dashboard', $fallbackParameters);
    }

    private function isAccessiblePage(Request $request, string $target): bool
    {
        $parts = parse_url($target);
        if (! is_array($parts) || isset($parts['user']) || isset($parts['pass'])
            || str_contains($target, '\\') || preg_match('/[\x00-\x20\x7f]/', $target)) {
            return false;
        }
        // Intended URLs are generated by Laravel, and must belong to this app/origin.
        if (($parts['scheme'] ?? null) !== $request->getScheme()
            || ($parts['host'] ?? null) !== $request->getHost()
            || ($parts['port'] ?? ($parts['scheme'] === 'https' ? 443 : 80)) !== $request->getPort()) {
            return false;
        }
        $path = $parts['path'] ?? '/';
        $base = $request->getBaseUrl();
        if ($base !== '' && ! str_starts_with($path, $base.'/')) {
            return false;
        }

        try {
            $route = $this->router->getRoutes()->match(Request::create($target, 'GET', server: $request->server->all()));
        } catch (NotFoundHttpException|MethodNotAllowedHttpException) {
            return false;
        }

        return match ($route->getName()) {
            'dashboard', 'profile.edit', 'contas.create', 'contas.index' => true,
            'contas.show', 'contas.edit', 'contas.legacyShow' => $request->user()->contas()->whereKey($route->parameter('conta'))->exists(),
            'admin.seasons.index' => $request->user()->role === 'admin',
            'admin.index' => in_array($request->user()->role, ['admin', 'mod'], true),
            default => false, // Auth forms, JSON progress and mutation endpoints are not landing pages.
        };
    }
}
